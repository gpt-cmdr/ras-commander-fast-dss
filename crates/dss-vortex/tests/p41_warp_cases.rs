//! The 60 P41 warp cases, with no oracle at run time: CI on any platform proves the same bits.
//!
//! Inputs and expected output digests come from Vortex 1.1.0 on public NOAA samples
//! (`fixtures/public/vortex_p41/`, see its row in `fixtures/public/README.md`). `warp_port/mod.rs`
//! is the P41 test port of the GDAL 3.2.1 and PROJ 7.2.0 logic, not the production warp, which
//! belongs to P44. Each case checks two things:
//!
//! - the output digest, against Vortex's float32 output (every NaN digested as one value);
//! - the digest of every maths call in order, inputs and result bits, against the committed value.
//!   This is the reached corpus, regenerated by the run itself.

use std::fmt::Write as _;
use std::fs;
use std::io::Read;
use std::path::PathBuf;

#[allow(dead_code, non_snake_case, clippy::all)]
mod warp_port;

const FNV_OFFSET: u64 = 0xcbf2_9ce4_8422_2325;
const FNV_PRIME: u64 = 0x0000_0100_0000_01b3;

fn fixture_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../fixtures/public/vortex_p41")
}

fn load_input(product: &str) -> Vec<f32> {
    let path = fixture_dir().join(format!("{product}.f32.zst"));
    let file = fs::read(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let mut decoder = ruzstd::decoding::StreamingDecoder::new(file.as_slice()).unwrap();
    let mut raw = Vec::new();
    decoder.read_to_end(&mut raw).unwrap();
    assert_eq!(raw.len() % 4, 0, "{product}: trailing bytes");
    raw.as_chunks::<4>()
        .0
        .iter()
        .map(|b| f32::from_le_bytes(*b))
        .collect()
}

fn output_digest(out: &[f32]) -> (usize, u64) {
    let (mut valid, mut h) = (0, FNV_OFFSET);
    for v in out {
        let word = if v.is_nan() {
            0x7fc0_0000
        } else {
            valid += 1;
            v.to_bits()
        };
        for b in word.to_le_bytes() {
            h ^= u64::from(b);
            h = h.wrapping_mul(FNV_PRIME);
        }
    }
    (valid, h)
}

#[test]
fn every_p41_case_gives_vortex_bits_and_the_committed_maths_stream() {
    let cases = fs::read_to_string(fixture_dir().join("cases.txt")).unwrap();
    let streams = include_str!("data/p41_call_streams.txt");
    let mut expected_streams = std::collections::HashMap::new();
    for line in streams
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
    {
        let p: Vec<&str> = line.split_whitespace().collect();
        expected_streams.insert(
            p[0].to_string(),
            (p[1].to_string(), p[2].parse::<u64>().unwrap()),
        );
    }
    let mut inputs = std::collections::HashMap::new();
    let (mut report, mut failures, mut count) = (String::new(), Vec::new(), 0);
    let mut total_cells = 0usize;
    for line in cases
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
    {
        let p: Vec<&str> = line.split_whitespace().collect();
        assert_eq!(p.len(), 25, "bad case row: {line}");
        let f = |i: usize| f64::from_bits(u64::from_str_radix(p[i], 16).unwrap());
        let data = inputs
            .entry(p[1].to_string())
            .or_insert_with(|| load_input(p[1]));
        let case = warp_port::Case {
            method: p[2],
            proj: p[3],
            nx: p[4].parse().unwrap(),
            ny: p[5].parse().unwrap(),
            ox: f(6),
            dx: f(7),
            oy: f(8),
            dy: f(9),
            nodata: f(10),
            te: [f(11), f(12), f(13), f(14)],
            tr: f(15),
            r: f(16),
            lat1: f(17),
            lat2: f(18),
            lat0: f(19),
            lon0: f(20),
            k: f(21),
        };
        let (out, calls, stream) = warp_port::run(&case, data);
        let (cells, valid, want) = (
            p[22].parse::<usize>().unwrap(),
            p[23].parse::<usize>().unwrap(),
            p[24],
        );
        let (got_valid, digest) = output_digest(&out);
        total_cells += out.len();
        count += 1;
        if out.len() != cells || got_valid != valid || format!("{digest:016x}") != want {
            failures.push(format!(
                "{}: cells {} want {cells}, valid {got_valid} want {valid}, digest {digest:016x} want {want}",
                p[0],
                out.len()
            ));
        }
        writeln!(report, "{} {stream:016x} {calls}", p[0]).unwrap();
        match expected_streams.get(p[0]) {
            Some((s, c)) if *s == format!("{stream:016x}") && *c == calls => {}
            other => failures.push(format!(
                "{}: maths stream {stream:016x} ({calls} calls), want {other:?}",
                p[0]
            )),
        }
    }
    if std::env::var_os("P44A_WRITE_STREAMS").is_some() {
        print!("{report}");
    }
    assert_eq!(count, 60, "the fixture must hold all 60 cases");
    assert_eq!(total_cells, 43_519_008);
    assert!(
        failures.is_empty(),
        "{} differ:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
