"""DSS6 regular blocks whose stored values are all missing (P28 addition).

HEC reports "no data" for such a block (DSS6 `zrrtsi.f` line 651 `ISTAT = 4`, mapped to
-1 by `ztsRetrieveReg6.c` and to -2 by Monolith `HecTimeSeries.read`; Monolith 3.3.27
returns -2 for both all-missing blocks of this fixture). The engine returns the block:
values NaN, raw values -901/-902 (docs/format/dss6.md §7.4). The opt-in refusal
(``no_data="refuse"``, P29) is tested in ``test_no_data6.py``.

``synthetic_all_missing6.dss`` is generated by ``crates/dss-core/tests/dss6_all_missing.rs``
(byte-checked there).
"""

import numpy as np
import pytest

import ras_commander_fast_dss as dss
from conftest import fixture_path

FIX = "synthetic_all_missing6.dss"
M_2000 = "/P28/GAGE M/FLOW/01JAN2000/1DAY/OBS/"
Q_2000 = "/P28/GAGE Q/FLOW/01JAN2000/1DAY/OBS/"


@pytest.fixture
def f():
    with dss.open(fixture_path(FIX)) as fh:
        yield fh


def test_all_missing_block_is_returned_as_nan(f):
    df = f.read_record(M_2000)
    assert len(df) == 366
    assert df["value"].isna().all()


def test_raw_values_keep_the_stored_markers(f):
    raw = f.read_record(M_2000, raw=True)["value"].to_numpy()
    assert len(raw) == 366 and (raw == -901.0).all()
    q = f.read_record(Q_2000, raw=True)["value"].to_numpy()
    assert np.isin(q, (-901.0, -902.0)).all() and q[1] == -902.0
    assert f.read_record(Q_2000)["value"].isna().all()


def test_neighbouring_block_with_data_reads(f):
    v = f.read_record("/P28/GAGE M/FLOW/01JAN2001/1DAY/OBS/")["value"].to_numpy()
    assert len(v) == 365 and v[0] == 0.0 and v[-1] == 364.0


ONLY_MISSING = [
    "/P28/GAGE Q/FLOW//1DAY/OBS/",  # -901/-902 alternating
    "/P28/GAGE R/FLOW//1DAY/OBS/",  # RTD (doubles), all -901
    "/P28/GAGE W/FLOW//1DAY/OBS/",  # with quality, all -901
    "/P28/GAGE N/FLOW//1DAY/OBS/",  # all -902
]


@pytest.mark.parametrize("path", ONLY_MISSING)
def test_dataset_of_only_all_missing_blocks(f, path):
    # trim_missing=False: every slot of the block, NaN (raw keeps the markers).
    df = f.read_timeseries(path, trim_missing=False)
    assert len(df) == 366 and df["value"].isna().all()
    raw = f.read_timeseries(path, trim_missing=False, raw=True)["value"].to_numpy()
    assert np.isin(raw, (-901.0, -902.0)).all()
    # Default: trimmed as heclib ztsTrim trims. read_arrays gives no values (no error);
    # read_timeseries reports "no data" as it does for any read with no values left.
    d = f.read_arrays(path)
    assert len(d["values"]) == 0 and len(d["times"]) == 0
    with pytest.raises(dss.DssPathnameNotFoundError):
        f.read_timeseries(path)


def test_record_types_and_quality(f):
    r = f.read_record("/P28/GAGE R/FLOW/01JAN2000/1DAY/OBS/", raw=True)
    assert len(r) == 366 and (r["value"].to_numpy() == -901.0).all()
    w = f.read_record("/P28/GAGE W/FLOW/01JAN2000/1DAY/OBS/", raw=True, include_quality=True)
    assert (w["value"].to_numpy() == -901.0).all() and (w["quality"].to_numpy() == 3).all()
    n = f.read_record("/P28/GAGE N/FLOW/01JAN2000/1DAY/OBS/", raw=True)["value"].to_numpy()
    assert (n == -902.0).all()
    # -FLT_MAX is not an all-missing block for HEC (Monolith reads it), but the Python
    # layer maps the marker to NaN all the same.
    x = f.read_record("/P28/GAGE X/FLOW/01JAN2000/1DAY/OBS/")
    assert len(x) == 366 and x["value"].isna().all()


def test_dataset_with_a_data_block_both_settings(f):
    path = "/P28/GAGE M/FLOW//1DAY/OBS/"
    full = f.read_timeseries(path, trim_missing=False)
    assert len(full) == 366 + 365
    assert full["value"].iloc[:366].isna().all() and full["value"].iloc[366] == 0.0
    trimmed = f.read_timeseries(path)
    assert len(trimmed) == 365 and trimmed["value"].iloc[0] == 0.0
