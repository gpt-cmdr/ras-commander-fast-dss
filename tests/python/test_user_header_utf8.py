"""DSS6 user-header text decoding.

The text bytes, after the NUL cut and the trailing-blank
trim, are decoded as UTF-8 when they are valid UTF-8 (else Java modified UTF-8);
otherwise, since P31, as UTF-8 with each malformed sequence replaced by one U+FFFD, as
Java's decoder does (``"utf-8-replaced"``; earlier versions used whole-text Latin-1). The same decode
feeds ``user_header_text``/``user_header_items``, dataframe ``attrs`` and the DSS6
location ``supplemental*`` fields. Raw bytes are unchanged.

``synthetic_userheader_utf8_6.dss`` is generated by
``crates/dss-core/tests/dss6_user_header_utf8.rs`` (byte-checked there).
"""

import pytest

import ras_commander_fast_dss as dss
from conftest import fixture_path

FIX = "synthetic_userheader_utf8_6.dss"

# pathname -> (raw text bytes as stored, expected text, expected encoding)
CASES = {
    "/P28/GAGE U/FLOW/01JAN2000/1HOUR/OBS/": (
        b"Gage: Y\xc3\xbd;VerticalDatum: NAVD88;Note: \xe2\x82\xac 5",
        "Gage: Yý;VerticalDatum: NAVD88;Note: € 5",
        "utf-8",
    ),
    "/P28/GAGE L/FLOW/01JAN2000/1HOUR/OBS/": (
        b"Gage: Caf\xe9;Note: Y\xc3\xbd",
        "Gage: Caf�;Note: Yý",
        "utf-8-replaced",
    ),
    "/P28/GAGE A/FLOW/01JAN2000/1HOUR/OBS/": (
        b"Gage: plain;Note: ascii",
        "Gage: plain;Note: ascii",
        "utf-8",
    ),
    "/P28/GAGE N/FLOW/01JAN2000/1HOUR/OBS/": (
        b"Gage: Y\xc3\x00\xbd;Hidden: 1",
        "Gage: Y�",
        "utf-8-replaced",
    ),
    "/P28/GAGE E/FLOW/01JAN2000/1HOUR/OBS/": (
        b"Gage: Y\xc3",
        "Gage: Y�",
        "utf-8-replaced",
    ),
    "/P28/GAGE T/FLOW/01JAN2000/1HOUR/OBS/": (
        b"Gage: x\xe2\x82    ",
        "Gage: x�",
        "utf-8-replaced",
    ),
    "/P28/GAGE V/FLOW/01JAN2000/1HOUR/OBS/": (
        b"Gage: Y\xc3\xbd\x00\xe9\xe9\xe9",
        "Gage: Yý",
        "utf-8",
    ),
    "/P28/GAGE I/STAGE/01JAN2000/IR-MONTH/OBS/": (
        b"Gage: \xc3\xa9t\xc3\xa9\x00",
        "Gage: été",
        "utf-8",
    ),
    # Java modified UTF-8: a surrogate pair for U+1F30A and C0 80 for U+0000.
    # Monolith 3.3.27 reads both the same way.
    "/P28/GAGE P/FLOW/01JAN2000/1HOUR/OBS/": (
        b"Note: wave \xed\xa0\xbc\xed\xbc\x8a\x00",
        "Note: wave \U0001f30a",
        "modified-utf-8",
    ),
    "/P28/GAGE Z/FLOW/01JAN2000/1HOUR/OBS/": (
        b"Gage: Z\xc0\x80;Note: after",
        "Gage: Z\x00;Note: after",
        "modified-utf-8",
    ),
}


@pytest.fixture
def f():
    with dss.open(fixture_path(FIX)) as fh:
        yield fh


@pytest.mark.parametrize("path", list(CASES))
def test_record_text_and_encoding(f, path):
    raw, text, enc = CASES[path]
    d = f.read_record_arrays(path)
    assert d["user_header_text"] == text
    assert d["user_header_encoding"] == enc
    # Raw bytes unchanged (blank-padded to whole words).
    assert d["user_header_bytes"] == raw + b" " * (-len(raw) % 4)
    assert d["user_header_items"] == dss.parse_user_header_items(text)


def test_valid_utf8_items_and_attrs(f):
    path = "/P28/GAGE U/FLOW/01JAN2000/1HOUR/OBS/"
    d = f.read_record_arrays(path)
    assert d["user_header_items"] == {
        "Gage": " Yý",
        "VerticalDatum": " NAVD88",
        "Note": " € 5",
    }
    df = f.read_timeseries(path, extra_attrs=True)
    assert df.attrs["user_header_text"] == CASES[path][1]
    assert df.attrs["user_header_encoding"] == "utf-8"
    df = f.read_timeseries("/P28/GAGE L/FLOW/01JAN2000/1HOUR/OBS/", extra_attrs=True)
    assert df.attrs["user_header_text"] == "Gage: Caf�;Note: Yý"
    assert df.attrs["user_header_encoding"] == "utf-8-replaced"


@pytest.mark.parametrize("path", list(CASES))
def test_location_supplemental_same_decode(f, path):
    raw, text, enc = CASES[path]
    loc = f.read_associated_location(path)
    assert loc.supplemental_source == "dss6_user_header"
    assert loc.supplemental == text
    assert loc.supplemental == f.read_record_arrays(path)["user_header_text"]
    assert loc.supplemental_encoding == enc
    # Raw text bytes: up to the first NUL, trailing blanks removed, undecoded.
    assert loc.supplemental_bytes == raw.split(b"\x00")[0].rstrip(b" ")
    assert loc.to_dict()["supplemental_encoding"] == enc


def test_location_items_and_datum_from_utf8_text(f):
    loc = f.read_associated_location("/P28/GAGE U/FLOW/01JAN2000/1HOUR/OBS/")
    assert loc.supplemental_items["Gage"] == " Yý"
    assert loc.supplemental_vertical_datum == " NAVD88"
    assert loc.vertical_datum_code == 0 and loc.vertical_datum_unknown  # text only


def test_dataset_reports_last_block_decoded_alone(f):
    d = f.read_arrays("/P28/GAGE D/FLOW//1HOUR/OBS/")
    assert d["user_header_block"] == "/P28/GAGE D/FLOW/01FEB2000/1HOUR/OBS/"
    assert d["user_header_text"] == "Gage: D �"
    assert d["user_header_encoding"] == "utf-8-replaced"
    assert d["user_header_conflict"] is True  # JAN stores other bytes (UTF-8 "é")
    jan = f.read_record_arrays("/P28/GAGE D/FLOW/01JAN2000/1HOUR/OBS/")
    assert jan["user_header_text"] == "Gage: D é" and jan["user_header_encoding"] == "utf-8"


def test_dss7_reads_have_no_encoding_and_location_stays_latin1():
    with dss.open(fixture_path("synthetic_location7.dss")) as f7:
        a = f7.read_location("/P15 SYNTH/GAGE A/Location Info////")
        assert a.supplemental_encoding == "latin-1"
        cat = f7.catalog()
        ts = cat[cat["record_type"].between(100, 119)]["pathname"].iloc[0]
        assert f7.read_record_arrays(ts)["user_header_encoding"] is None
    # A DSS7 location whose values2 holds C3 BD (valid UTF-8 for "ý") and
    # a lone E9. It must stay Latin-1: a UTF-8 decode would give "ý" and fail here.
    with dss.open(fixture_path("synthetic_location_latin1_7.dss")) as f7:
        loc = f7.read_location("/P28 LOC/GAGE L7/Location Info////")
    assert loc.supplemental_source == "dss7_location_record"
    assert loc.supplemental_bytes == b"Note:Y\xc3\xbd;Owner:Caf\xe9;"
    assert loc.supplemental == "Note:YÃ½;Owner:Café;"
    assert loc.supplemental_encoding == "latin-1"
    assert loc.supplemental_items["Note"] == "YÃ½"


def test_empty_text_has_no_encoding():
    # No text (blank-only header here) gives user_header_encoding None and
    # no attr, as supplemental_encoding is None without supplemental text.
    with dss.open(fixture_path("synthetic_location_uh6.dss")) as f6:
        p = "/P27/GAGE L/FLOW/01JAN2000/1HOUR/OBS/"
        d = f6.read_record_arrays(p)
        assert len(d["user_header_words"]) > 0 and d["user_header_text"] == ""
        assert d["user_header_encoding"] is None
        assert "user_header_encoding" not in f6.read_timeseries(p, extra_attrs=True).attrs
        assert f6.read_associated_location(p).supplemental_encoding is None
