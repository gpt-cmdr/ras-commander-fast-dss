"""P33: DSS6 variants written by HEC software, read through the Python API and checked
against values HEC Monolith 3.3.27 read back (``synthetic_hec6_reference.tsv``).

Fixtures (HEC Monolith 3.3.27, javaHeclib ``7-IU``,
``evidence/P33/scripts/P33Monolith.java``; not regenerated by tests):

- ``synthetic_hec_compress6.dss``: regular float blocks stored with compression schemes
  1-5 (``Heclib.zsrtsx``), the 3-significant-digit schemes 4/5 included;
- ``synthetic_hec_variants6.dss``: quality on 100/105/110/115, IR-CENTURY, IR-DECADE and
  far-date irregular data, an irregular pattern (type 111), pseudo-regular paths, and a
  write that offered notes (DSS6 has none).

All names and values are synthetic.
"""

import hashlib
import struct
from datetime import datetime

import numpy as np
import pytest

import ras_commander_fast_dss as dss
from conftest import fixture_path

COMPRESS = "synthetic_hec_compress6.dss"
VARIANTS = "synthetic_hec_variants6.dss"
REFERENCE = "synthetic_hec6_reference.tsv"
SHA = {
    COMPRESS: "e571c99b0ffc568c09bdc82de2acf78c992ff4704c92c0d47d8d105b2eb41df5",
    VARIANTS: "6bd643bb05534aee376425c9859ea94cab19509d523b787139ee293b83cda773",
    REFERENCE: "f4b0e0091a49923e513c8cc3481f1acde588b06ba476fb3196b500d7e6954cc3",
}
UNDEF = -float(np.finfo(np.float32).max)


def _ref(kind):
    lines = fixture_path(REFERENCE).read_text(encoding="utf-8").split("\n")
    return [l.split("\t") for l in lines if l and not l.startswith("#") and l.split("\t")[0] == kind]


def _when(s):
    d = datetime.strptime(s[:9], "%d%b%Y")
    secs = int((d - datetime(1899, 12, 31)).total_seconds()) + int(s[10:12]) * 3600 + int(s[12:14]) * 60
    return np.datetime64("1899-12-31T00:00:00") + np.timedelta64(secs, "s")


def _read(f, mode, path, a, b):
    if mode == "REC":
        return f.read_record_arrays(path)
    if mode == "ALL":
        return f.read_arrays(path)
    return f.read_arrays(path, _when(a), _when(b))


def _as_monolith(values):
    """float64 values with HEC's -901/-902 shown as Monolith shows them (-FLT_MAX)."""
    v = np.asarray(values, dtype=np.float64).copy()
    v[(v == -901.0) | (v == -902.0)] = UNDEF
    return v


@pytest.mark.parametrize("name", sorted(SHA))
def test_fixture_sha256(name):
    assert hashlib.sha256(fixture_path(name).read_bytes()).hexdigest() == SHA[name]


@pytest.mark.parametrize("name", [COMPRESS, VARIANTS])
def test_catalog_equals_monolith(name):
    want = {r[2] for r in _ref("CAT") if r[1] == name}
    count = [int(r[2]) for r in _ref("FILE") if r[1] == name]
    with dss.open(fixture_path(name)) as f:
        got = set(f.catalog()["pathname"])
    assert got == want and count == [len(want)]
    if name == VARIANTS:
        # Pseudo-regular blocks are listed with their `~` E part, as HEC displays them.
        assert "/P33/PSEUDO/FLOW/01JAN2000/~1WEEK/PS/" in got


@pytest.mark.parametrize("row", _ref("RAW"), ids=lambda r: r[2])
def test_record_bits_equal_heclib(row):
    _, name, path, scheme, n, bits = row
    with dss.open(fixture_path(name)) as f:
        d = f.read_record_arrays(path)
    v = np.asarray(d["values"])
    assert v.dtype == np.float32 and len(v) == int(n)
    want = np.array([int(h, 16) for h in bits.split(",")], dtype=np.uint32)
    assert np.array_equal(v.view(np.uint32), want)


def test_raw_rows_cover_every_scheme():
    assert sorted({int(r[3]) for r in _ref("RAW")}) == [0, 1, 2, 3, 4, 5]


@pytest.mark.parametrize("row", _ref("SERIES"), ids=lambda r: f"{r[2]} {r[3]} {r[4]}")
def test_series_equal_monolith(row):
    _, name, mode, path, a, b, n, mins, bits, qual = row
    with dss.open(fixture_path(name)) as f:
        d = _read(f, mode, path, a, b)
    n = int(n)
    assert len(d["values"]) == n
    times = np.asarray(d["times"], dtype=np.int64)
    want_t = np.array([int(x) for x in mins.split(",")] if n else [], dtype=np.int64) * 60
    assert np.array_equal(times, want_t)
    want_v = np.array([struct.unpack("<d", struct.pack("<Q", int(h, 16)))[0] for h in bits.split(",")]
                      if n else [], dtype=np.float64)
    assert np.array_equal(_as_monolith(d["values"]).view(np.uint64), want_v.view(np.uint64))
    q = d["quality"]
    want_q = None if qual == "-" else np.array([int(x) for x in qual.split(",")], dtype=np.int64)
    if want_q is not None and not want_q.any() and q is None:
        want_q = None  # Monolith reports zeros for records without quality
    if want_q is None:
        assert q is None
    else:
        assert np.array_equal(np.asarray(q, dtype=np.int64), want_q)


@pytest.mark.parametrize("row", _ref("SUMMARY"), ids=lambda r: f"{r[2]} {r[3]} {r[4]}")
def test_summary_equal_monolith(row):
    _, name, mode, path, a, b, n, first, last, sha = row
    with dss.open(fixture_path(name)) as f:
        d = _read(f, mode, path, a, b)
    t = np.asarray(d["times"], dtype=np.int64)
    assert len(t) == int(n)
    assert t[0] == int(first) * 60 and t[-1] == int(last) * 60
    raw = _as_monolith(d["values"]).astype("<f8").tobytes()
    assert hashlib.sha256(raw).hexdigest() == sha


def test_sig_digit_values_through_the_dataframe():
    with dss.open(fixture_path(COMPRESS)) as f:
        df = f.read_timeseries("/P33/SIG5 RUNS/PRECIP-INC//1HOUR/S5/")
        raw = f.read_record_arrays("/P33/SIG4 SPAN/FLOW/01JAN2000/1DAY/S4/")["values"]
    # Day 1 is a run of zeros, day 2 of 0.12; days 4, 10, ... are -901 (NaN here).
    assert df["value"].iloc[0] == 0.0
    assert df["value"].iloc[30] == np.float32(0.12)
    assert df["value"].iloc[72:96].isna().all()
    # R2SD3: -FLT_MAX is stored as the overflow code 1005 and reads as -1.0e37; 999.5
    # rounds to 1000; 0.012345 keeps two digits (INT truncates LOG10 toward zero).
    assert raw[42] == np.float32(-1.0e37)
    assert raw[18] == np.float32(1000.0)
    assert raw[30] == np.float32(0.012)


def test_irregular_pattern_pairs():
    # Monolith 3.3.27 and HEC-DSSVue misread this record through the DSS7 layout of
    # Public/ztsRetrievePattern.c (8 garbled values); zritsi6.f reads the stored pairs.
    with dss.open(fixture_path(VARIANTS)) as f:
        d = f.read_record_arrays("/P33/IPAT/FLOW/TS-PATTERN/IR-YEAR/PAT/")
    assert d["record_type"] == 111 and d["pattern"]
    assert np.array_equal(d["values"], np.array([0.1, 0.4, 0.9, 0.3], dtype=np.float32))
    assert list(np.asarray(d["times"], dtype=np.int64)) == [m * 60 for m in (525600, 526200, 583200, 813600)]


def test_far_dates():
    with dss.open(fixture_path(VARIANTS)) as f:
        old = f.read_timeseries("/P33/FAR1066/FLOW//IR-YEAR/FAR/")
        new = f.read_timeseries("/P33/FAR5900/FLOW//IR-YEAR/FAR/")
        cen = f.read_arrays("/P33/CENTURY/FLOW//IR-CENTURY/FAR/")
    assert old["value"].tolist() == [4.0, 5.0, 6.0]
    assert new["value"].tolist() == [7.0, 8.0, 9.0]
    assert len(cen["values"]) == 30
