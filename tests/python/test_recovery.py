@pytest.mark.parametrize(
    "content",
    [b"", b"not a dss file at all", b"\0" * (1 << 20), b"ZDSS" + b"\0" * 17],
    ids=["empty", "text_stub", "zero_filled", "zdss_truncated"],
)
def test_negative_controls_fail_at_open(tmp_path, content):
    # Shapes of the golden negative controls (neg_empty_0B, neg_zero_filled_1MB,
    # neg_pytest_stub_21B): they never open, so no route can make them readable.
    p = tmp_path / "neg.dss"
    p.write_bytes(content)
    with pytest.raises(DssFormatError):
        dss.open(p)
    with pytest.raises(DssFormatError):
        dss.open(p, recover=True)


# -- integrity arms, built by patching tmp copies inside the tests ---------------------
# DSS6 layout: heclib_f/src/zinit6.f:ZINIT6 (info block: KIFLAG word 0, KINPAT 2,
# KIPATH 3.., then KIPASS at 3+P and KITYPE at 17+P, P = pathname words); 1-based word
# addresses with 127 words per 512-byte record (zgetrw6.f:ZGETRW6). DSS7 layout:
# docs/format/dss7.md §5.1 (info flag word 0, hash word 3) and §3.4 (bin entry: status
# word 1, type in the low half of word 4).

PY6 = "synthetic_python6.dss"
PY6_TS = "/TS-BASIN/B/FLOW/01JAN2000/1HOUR/F/"


def _w6_byte(addr):
    a = addr - 1
    return (a // 127) * 512 + (a % 127) * 4


def _b6_word(off):
    return (off // 512) * 127 + (off % 512) // 4 + 1


def _patched(tmp_path, name, edits):
    b = bytearray(fixture_path(name).read_bytes())
    for off, data in edits:
        b[off : off + len(data)] = data
    p = tmp_path / name
    p.write_bytes(bytes(b))
    return p


def _i32(v):
    return int(v).to_bytes(4, "little", signed=True)


def _i64(v):
    return int(v).to_bytes(8, "little", signed=True)


def _entry(name, pathname):
    with dss.open(fixture_path(name)) as f:
        i = _rows(f)[pathname]
        return i, f.diagnose(i)


def _dss6_info_edits(word_edits):
    i, d = _entry(PY6, PY6_TS)
    base = _b6_word(d["info_address"])
    p = (len(PY6_TS) - 1) // 4 + 1
    return i, p, [(_w6_byte(base + k(p)), _i32(v)) for k, v in word_edits]


@pytest.mark.parametrize(
    "edits, problem",
    [
        ([(lambda p, k=k: k, 0) for k in range(28 + 9)], "zeroed"),
        ([(lambda p: 0, 12345)], "bad_flag"),
        ([(lambda p: 3, int.from_bytes(b"/XS-", "little", signed=True))], "pathname_mismatch"),
    ],
    ids=["zeroed", "bad_flag", "pathname_mismatch"],
)
def test_dss6_info_integrity_arms(tmp_path, edits, problem):
    i, _, raw = _dss6_info_edits(edits)
    with dss.open(_patched(tmp_path, PY6, raw)) as f:
        d = f.diagnose(i)
        assert (d["outcome"], d["info_problem"], d["readable"]) == ("unavailable", problem, False)
        with pytest.raises(DssRecordUnavailableError) as ei:
            f.read_record_at(i)
        assert ei.value.problem == problem and ei.value.index == i


def test_dss6_password_protected_is_not_readable(tmp_path):
    # zrdinf6.f:ZRDINF6 lines 65-70: KIPASS set on a 6-E or later file denies access.
    i, _, raw = _dss6_info_edits([(lambda p: 3 + p, 1)])
    with dss.open(_patched(tmp_path, PY6, raw)) as f:
        d = f.diagnose(i)
        assert d["password_protected"] and d["outcome"] == "unsupported_record_type"
        assert not d["readable"]
        with pytest.raises(dss.DssError) as ei:
            f.read_record_at(i)
        assert not isinstance(ei.value, DssRecordUnavailableError)


@pytest.mark.parametrize("rtype", [102, 106, 120])
def test_dss6_type_outside_decoder_set_is_unsupported(tmp_path, rtype):
    # Dss6File::decode_ts_info reads only KITYPE 100/101/105/110/111/115.
    i, _, raw = _dss6_info_edits([(lambda p: 17 + p, rtype)])
    with dss.open(_patched(tmp_path, PY6, raw)) as f:
        d = f.diagnose(i)
        assert not d["ts_supported"] and d["outcome"] == "unsupported_record_type"
        with pytest.raises(DssUnsupportedRecordError):
            f.read_record_at(i)


@pytest.mark.parametrize(
    "word, value, problem",
    [(0, 7, "bad_flag"), (3, None, "hash_mismatch")],
    ids=["bad_flag", "hash_mismatch"],
)
def test_dss7_info_integrity_arms(tmp_path, word, value, problem):
    i, d = _entry(FIXTURE, REACHABLE)
    off = d["info_address"] + 8 * word
    if value is None:  # flip the stored info hash
        cur = int.from_bytes(fixture_path(FIXTURE).read_bytes()[off : off + 8], "little", signed=True)
        value = cur + 1
    with dss.open(_patched(tmp_path, FIXTURE, [(off, _i64(value))])) as f:
        d = f.diagnose(i)
        assert (d["outcome"], d["info_problem"]) == ("unavailable", problem)
        with pytest.raises(DssRecordUnavailableError) as ei:
            f.read_record_at(i)
        assert ei.value.problem == problem
        # Ordinary reads are unchanged: a reused info block is "not found" (zreadInfo).
        if problem == "hash_mismatch":
            with pytest.raises(DssPathnameNotFoundError):
                f.read_record(REACHABLE)


@pytest.mark.parametrize("rtype", [102, 103, 117, 199])
def test_dss7_type_outside_decoder_set_is_unsupported(tmp_path, rtype):
    # diagnose and read_record_at agree: only 100/101/105/106/110/111/115/116 decode.
    i, d = _entry(FIXTURE, REACHABLE)
    with dss.open(_patched(tmp_path, FIXTURE, [(d["bin_entry_address"] + 32, _i32(rtype))])) as f:
        d = f.diagnose(i)
        assert d["record_type"] == rtype and not d["ts_supported"]
        assert d["outcome"] == "unsupported_record_type" and not d["readable"]
        with pytest.raises(DssUnsupportedRecordError):
            f.read_record_at(i)


def test_dss7_non_live_entry_is_not_chain_checked(tmp_path):
    # walk.rs skips the hash-chain check for non-live entries (ChainState::NotChecked).
    i, d = _entry(FIXTURE, REACHABLE)
    with dss.open(_patched(tmp_path, FIXTURE, [(d["bin_entry_address"] + 8, _i64(11))])) as f:
        d = f.diagnose(i)
        assert d["status"] == "deleted" and d["hash_chain"] == "not_checked"
        assert d["outcome"] == "not_live" and not d["reachable_by_lookup"]
        with pytest.raises(IndexError):
            f.read_record_at(i)


def test_diagnose_pathname_folding_is_ascii_only(damaged):
    assert len(damaged.diagnose(REACHABLE.lower())) == 1
    # U+017F (long s) upper-cases to ASCII "S" in Unicode folding; Rust does not.
    assert "\u017f".upper() == "S"
    assert damaged.diagnose(REACHABLE.replace("SYN", "\u017fYN")) == []


def test_readable_agrees_with_read_record_at_on_every_entry():
    for name in [FIXTURE] + ALL:
        for recover in (False, True):
            with dss.open(fixture_path(name), recover=recover) as f:
                for i in range(len(f.catalog(all_entries=True))):
                    d = f.diagnose(i)
                    try:
                        f.read_record_at(i)
                        ok = True
                    except (dss.DssError, IndexError):
                        ok = False
                    assert ok == d["readable"], (name, recover, i, d["outcome"])
