"""DSS6 location supplemental text from the time-series user header (P27, decision D37).

Monolith reports a DSS6 time series' user header as its ``supplementalInfo``; HEC's C
library leaves the location's supplemental text empty. The engine fills
``Location.supplemental`` from the same record's user header, tags it with
``supplemental_source``, and changes nothing else: coordinates, codes, the presence
rule and the typed vertical datum come from the internal header only.

``synthetic_location_uh6.dss`` is generated by
``crates/dss-core/tests/dss6_location_supplemental.rs``. See
``evidence/P27/REPORT.md``.
"""

import pytest

import ras_commander_fast_dss as dss
from ras_commander_fast_dss import DssLocationConflictError

from conftest import fixture_path

LUH6 = "synthetic_location_uh6.dss"
H_JAN = "/P27/GAGE H/FLOW/01JAN2000/1HOUR/OBS/"
H_MAR = "/P27/GAGE H/FLOW/01MAR2000/1HOUR/OBS/"
H_DEC = "/P27/GAGE H/FLOW/01DEC2000/1HOUR/OBS/"
I_IRR = "/P27/GAGE I/STAGE/01JAN2000/IR-MONTH/OBS/"
I_MAR = "/P27/GAGE I/STAGE/01MAR2000/IR-MONTH/OBS/"
N_JAN = "/P27/GAGE N/STAGE/01JAN2000/IR-MONTH/OBS/"
N_BAD = "/P27/GAGE N/STAGE/NOTADATE/IR-MONTH/OBS/"
TEXT_H_JAN = "Gage: H1;VerticalDatum: NAVD88;Note: january"
TEXT_H_MAR = "Gage: H2;VerticalDatum: NAVD88;Note: march"
TEXT_H_DEC = "Gage: H3;VerticalDatum: NAVD88;Note: december"
TEXT_I = "Gage: I1;VerticalDatum: NAVD88;"
TEXT_I_MAR = "Gage: I3;Note: march"
TEXT_N_JAN = "Gage: N1;Note: dated block"
TEXT_N_BAD = "Gage: N0;Note: undated block"


@pytest.fixture
def f6():
    with dss.open(fixture_path(LUH6)) as f:
        yield f


def test_text_from_user_header(f6):
    loc = f6.read_associated_location(H_JAN)
    assert loc.source == "dss6_ts_header"
    assert loc.supplemental_source == "dss6_user_header"
    assert loc.supplemental == TEXT_H_JAN  # trailing blank padding removed
    assert loc.supplemental_bytes == TEXT_H_JAN.encode("latin-1")
    # HEC's location item convention (no trimming, first wins).
    assert loc.supplemental_items == {
        "Gage": " H1",
        "VerticalDatum": " NAVD88",
        "Note": " january",
    }
    # Same text as the time-series read reports (P26).
    assert loc.supplemental == f6.read_record_arrays(H_JAN)["user_header_text"]
    d = loc.to_dict()
    assert d["supplemental_source"] == "dss6_user_header"
    assert d["supplemental"] == TEXT_H_JAN


def test_typed_fields_unchanged_and_datum_text_informational(f6):
    loc = f6.read_associated_location(H_JAN)
    assert loc.coordinates == (-90.5, 30.25, 12.0)
    assert (loc.coordinate_system, loc.horizontal_units) == ("LAT_LONG", "DECIMAL_DEGREES")
    assert (loc.horizontal_datum, loc.vertical_units) == ("NAD83", "FEET")
    # The text names NAVD88; the typed datum stays unset (D37).
    assert loc.vertical_datum_code == 0 and loc.vertical_datum is None
    assert loc.vertical_datum_unknown is True and loc.vertical_datum_named is False
    assert loc.supplemental_vertical_datum == " NAVD88"
    assert loc.time_zone is None

    irr = f6.read_associated_location(I_IRR)
    assert irr.record_type == 110
    assert irr.supplemental == TEXT_I  # ends at the first NUL; junk after it is dropped
    assert "Hidden" not in irr.supplemental
    # Typed NGVD-29 is kept; the NAVD88 text does not override it.
    assert (irr.vertical_datum, irr.vertical_datum_code) == ("NGVD-29", 2)
    assert irr.supplemental_vertical_datum == " NAVD88"


def test_empty_header_gives_none(f6):
    for p in ("/P27/GAGE J/FLOW/01JAN2000/1HOUR/OBS/", "/P27/GAGE L/FLOW/01JAN2000/1HOUR/OBS/"):
        loc = f6.read_associated_location(p)
        assert loc is not None and loc.coordinates == (-90.5, 30.25, 12.0)
        assert loc.supplemental is None and loc.supplemental_bytes is None
        assert loc.supplemental_source is None
        assert loc.supplemental_items == {} and loc.supplemental_vertical_datum is None


def test_presence_rule_unchanged(f6):
    # User-header text without coordinates: no location.
    p = "/P27/GAGE K/FLOW/01JAN2000/1HOUR/OBS/"
    assert f6.read_record_arrays(p)["user_header_text"] == "Gage: K1"
    assert f6.read_associated_location(p) is None


def test_dataset_uses_reported_block(f6):
    # Catalog order JAN, DEC, MAR; date order JAN, MAR, DEC. The text and pathname are
    # those of the block HEC reports for the whole dataset (last by date, dss6.md §14.4),
    # which is neither the first nor the last block in catalog order.
    assert f6._p15_ts_blocks()[("P27", "GAGE H", "FLOW", "1HOUR", "OBS")] == [H_JAN, H_DEC, H_MAR]
    loc = f6.read_associated_location("/P27/GAGE H/FLOW//1HOUR/OBS/")
    assert loc.supplemental == TEXT_H_DEC
    assert loc.supplemental_source == "dss6_user_header"
    assert loc.pathname == H_DEC
    assert loc.requested_pathname == "/P27/GAGE H/FLOW//1HOUR/OBS/"
    assert loc.coordinates == (-90.5, 30.25, 12.0)
    rep = f6.read_arrays("/P27/GAGE H/FLOW//1HOUR/OBS/")
    assert rep["user_header_block"] == H_DEC
    assert loc.supplemental == rep["user_header_text"]
    # A full block pathname uses that block.
    assert f6.read_associated_location(H_MAR).supplemental == TEXT_H_MAR
    assert f6.read_associated_location(H_MAR).pathname == H_MAR
    # A D part that names no stored block reads the dataset.
    absent = f6.read_associated_location("/P27/GAGE H/FLOW/01APR2000/1HOUR/OBS/")
    assert (absent.supplemental, absent.pathname) == (TEXT_H_DEC, H_DEC)


def test_irregular_dataset_and_absent_block(f6):
    # Catalog order JAN, MAR (no FEB block): the reported block is MAR.
    assert f6._p15_ts_blocks()[("P27", "GAGE I", "STAGE", "IR-MONTH", "OBS")] == [I_IRR, I_MAR]
    loc = f6.read_associated_location("/P27/GAGE I/STAGE//IR-MONTH/OBS/")
    assert (loc.supplemental, loc.pathname, loc.record_type) == (TEXT_I_MAR, I_MAR, 110)
    assert (loc.vertical_datum, loc.coordinates) == ("NGVD-29", (-91.0, 31.0, 0.0))
    assert f6.read_arrays("/P27/GAGE I/STAGE//IR-MONTH/OBS/")["user_header_block"] == I_MAR
    # A location read is not a window read: a D part naming an absent block (between or
    # after the stored ones) reads the whole dataset and gives the last stored block's
    # text, although a P26 window read ending in that absent block reports no header.
    for d in ("01FEB2000", "01APR2000"):
        p = f"/P27/GAGE I/STAGE/{d}/IR-MONTH/OBS/"
        a = f6.read_associated_location(p)
        assert (a.supplemental, a.pathname, a.requested_pathname) == (TEXT_I_MAR, I_MAR, p)
    w = f6.read_arrays("/P27/GAGE I/STAGE//IR-MONTH/OBS/", "2000-01-01 00:00", "2000-02-15 00:00")
    assert w["user_header_text"] == "" and w["user_header_block"] is None


def test_undated_block_sorts_first(f6):
    # Catalog order: dated JAN block, then a block whose D part is not a date. The
    # undated block sorts first (DatasetIndex: julian None first), so JAN is reported.
    assert f6._p15_ts_blocks()[("P27", "GAGE N", "STAGE", "IR-MONTH", "OBS")] == [N_JAN, N_BAD]
    loc = f6.read_associated_location("/P27/GAGE N/STAGE//IR-MONTH/OBS/")
    assert (loc.supplemental, loc.pathname) == (TEXT_N_JAN, N_JAN)
    assert f6.read_associated_location(N_BAD).supplemental == TEXT_N_BAD


def test_coordinate_conflict_still_raises():
    with dss.open(fixture_path("synthetic_python6.dss")) as f:
        with pytest.raises(DssLocationConflictError):
            f.read_associated_location("/P15 LOC/DISAGREE/FLOW//1HOUR/OBS/")
        agree = f.read_associated_location("/P15 LOC/AGREE/FLOW//1HOUR/OBS/")
        assert agree.supplemental is None and agree.supplemental_source is None


def test_sample6_has_no_header_text():
    with dss.open(fixture_path("sample6.dss")) as f:
        loc = f.read_associated_location("/MISSISSIPPI/ST. LOUIS/FLOW/01JAN1861/1DAY/OBS/")
        assert loc.supplemental is None and loc.supplemental_source is None


def test_dss7_source_unchanged_except_tag():
    with dss.open(fixture_path("synthetic_location7.dss")) as f:
        a = f.read_location("/P15 SYNTH/GAGE A/Location Info////")
        assert a.supplemental_source == "dss7_location_record"
        assert a.supplemental == "VerticalDatum:NGVD29;Operator:Synthetic;Note:unknown typed datum;"
        assert a.vertical_datum_code == 0 and a.supplemental_vertical_datum == "NGVD29"
        # Stored empty text is still text stored by the record.
        b = f.read_location("/P15 SYNTH/GAGE B/Location Info////")
        assert b.supplemental == "" and b.supplemental_source == "dss7_location_record"
        assert f.read_associated_location(
            "/P15 SYNTH/GAGE A/STAGE/01Jan2020/1Hour/P15/"
        ).supplemental_source == "dss7_location_record"
