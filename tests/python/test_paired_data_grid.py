@pytest.mark.parametrize("name", sorted(PD_EXPECT))
def test_pd_public_fixtures_match_oracle_checksums(name):
    count, multi, labelled, expected = PD_EXPECT[name]
    with dss.open(fixture_path(name)) as f:
        records = [f.read_paired_data(p) for p in pd_pathnames(f)]
    assert len(records) == count
    assert sum(r.n_curves > 1 for r in records) == multi
    assert sum(bool(r.labels) for r in records) == labelled
    h = 0xCBF29CE484222325
    for r in sorted(records, key=lambda r: r.pathname.encode("latin-1")):
        assert r.record_type == 200 and r.stored_dtype == np.float32
        assert r.ordinates.dtype == np.float32 and r.values.dtype == np.float32
        assert r.values.shape == (r.n_curves, r.n_ordinates)
        assert r.dss_version == f.version
        h = fnv(h, r.pathname.encode("latin-1"))
        h = fnv(h, r.ordinates.astype("<f4").tobytes())
        h = fnv(h, r.values.astype("<f4").tobytes())  # curve-major, as stored
    assert h == expected


