@pytest.mark.parametrize("name", ["sample7.dss", "sample6.dss"])
def test_pd_typed_errors(name):
    with dss.open(fixture_path(name)) as f:
        for p in ["/NO/SUCH/STAGE-FLOW///RECORD/", "notapath", ""]:
            with pytest.raises(DssPathnameNotFoundError) as e:
                f.read_paired_data(p)
            assert str(e.value) == not_found_text(p)
            assert isinstance(e.value, ValueError) and isinstance(e.value, RuntimeError)
        ts = f.catalog().query("record_type == 100").pathname.iloc[0]
        with pytest.raises(DssUnsupportedRecordError, match="not paired data"):
            f.read_paired_data(ts)
        # A time series matched with its D part ignored is still the wrong type.
        parts = ts.split("/")
        parts[4] = "01JAN1800"
        with pytest.raises(DssUnsupportedRecordError, match="not paired data"):
            f.read_paired_data("/".join(parts))
        with pytest.raises(DssPathnameNotFoundError):
            f.read_paired_data("/".join(parts), ignore_d_part=False)
        # The time-series reader still refuses paired data, and grids too.
        with pytest.raises(DssUnsupportedRecordError):
            f.read_timeseries(ANACOSTIA)
        with pytest.raises(DssUnsupportedRecordError):
            f.read_grid(ANACOSTIA)


