def fnv(h: int, b: bytes) -> int:
    for x in b:
        h ^= x
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def pd_pathnames(f) -> list:
    cat = f.catalog()
    return cat.loc[cat.record_type.isin([200, 205]), "pathname"].tolist()


def not_found_text(pathname: str) -> str:
    return f"No data found for pathname: {pathname}"


