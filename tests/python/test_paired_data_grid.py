@pytest.mark.parametrize("name", GRID_FILES)
def test_grid_specified_legacy_zlib(name):
    with dss.open(fixture_path(name)) as f:
        g = f.read_grid(G_SPEC)
        assert isinstance(g, Grid)
        assert (g.grid_type, g.record_type, g.dss_version) == ("specified", 430, f.version)
        assert g.data.dtype == np.float32 and g.data.flags.c_contiguous and g.data.flags.writeable
        # P63: the result adopts the fresh native array (owndata is False: the memory is
        # owned through NumPy's base object), so check it is detached instead.
        assert not np.shares_memory(g.data, f.read_grid(G_SPEC).data)
        assert g.shape == g.data.shape == (2, 3)
        # Native order: row 0 is the bottom row; ravel() is the stored cell order.
        np.testing.assert_array_equal(g.data, [[1, 2, 3], [4, np.nan, 6]])
        up = f.read_grid(G_SPEC, order="north_up")
        np.testing.assert_array_equal(up.data, [[4, np.nan, 6], [1, 2, 3]])
        assert up.data.flags.c_contiguous
        raw = f.read_grid(G_SPEC, missing="raw")
        assert raw.data[1, 1] == U  # null marker normalized as Java heclib does
        audit = f.read_grid(G_SPEC, missing="raw", preserve_legacy_missing=True)
        assert audit.data[1, 1] == np.float32(-9999.0)
        np.testing.assert_array_equal(raw.missing_mask(), np.isnan(g.data))
        np.testing.assert_array_equal(audit.missing_mask(), np.isnan(g.data))
        assert (g.nx, g.ny, g.cell_size) == (3, 2, 2.0)
        assert (g.lower_left_cell_x, g.lower_left_cell_y) == (-2, 3)
        assert (g.x_coord_of_grid_cell_zero, g.y_coord_of_grid_cell_zero) == (10.0, 20.0)
        assert g.origin == (6.0, 26.0) and g.extent == (6.0, 26.0, 12.0, 30.0)
        assert (g.srs_name, g.wkt, g.srs_definition_type) == ("WKT", "GEOGCS[]", 0)
        assert (g.data_units, g.data_type, g.data_type_name) == ("MM", 1, "PER-CUM")
        assert (g.start_time, g.end_time) == (T0, T1)
        assert g.metadata["start_seconds"] == dss.to_hec_seconds("2020-01-01")
        assert (g.min_value, g.max_value, g.mean_value) == (1.0, 6.0, pytest.approx(3.2))
        assert g.range_limit_table.tolist() == [1.0, 4.0] and g.range_counts.tolist() == [5, 2]
        assert g.range_limit_table.dtype == np.float32 and g.range_counts.dtype == np.int32
        assert g.null_value == -9999.0
        assert (g.missing, g.order) == ("nan", "native")
        assert g.metadata["time_zone_id"] == "UTC"
        assert g.metadata["compression_method"] == 26
        assert g.metadata["struct_version"] > 0  # legacy flat header byte size


