def test_concurrent_reads_match_serial():
    path = fixture_path("Muncie.dss")
    with dss.open(path) as f:
        paths = pd_pathnames(f)[:200]
        serial = [f.read_paired_data(p).values.tobytes() for p in paths]
        with ThreadPoolExecutor(4) as ex:
            threaded = list(ex.map(lambda p: f.read_paired_data(p).values.tobytes(), paths))
    assert threaded == serial
    gpath = fixture_path("synthetic_grid7.dss")
    with dss.open(gpath) as f:
        with ThreadPoolExecutor(4) as ex:
            out = list(ex.map(lambda _: f.read_grid(G_MODERN, missing="raw").data.tobytes(), range(32)))
    assert len(set(out)) == 1


