def path(tag):
    return f"/PUBLIC/ALBERS-{tag}/PRECIP/01JAN2020:0000/01JAN2020:0100/SYNTH/"


@pytest.mark.parametrize("name, cases", [
    ("synthetic_albers6.dss", LEGACY),
    ("synthetic_albers7.dss", {**LEGACY, **MODERN}),
])
def test_albers_srs_matches_monolith(name, cases):
    with dss.open(fixture_path(name)) as f:
        cat = f.catalog()
        assert sorted(cat.pathname) == sorted(path(t) for t in cases)
        for tag, shg in cases.items():
            g = f.read_grid(path(tag))
            assert g.grid_type == "albers"
            np.testing.assert_array_equal(g.data, [[0.5, 1.0], [1.5, 2.0]], err_msg=tag)
            assert g.srs_definition == (SHG if shg else ""), tag
            assert g.wkt == g.srs_definition
            stored = g.metadata["stored_srs_definition"]
            if tag.startswith("L-"):
                assert stored is None and g.metadata["albers"]["datum"] in (0, 1, 2)
            else:
                assert isinstance(stored, str) and g.metadata["albers"] is not None


def test_modern_albers_keeps_stored_string():
    with dss.open(fixture_path("synthetic_albers7.dss")) as f:
        assert f.read_grid(path("M-TEST")).metadata["stored_srs_definition"] == "TEST"
        g = f.read_grid(path("M-SHG-X0"))
        assert (g.srs_definition, g.metadata["stored_srs_definition"]) == ("", SHG)
        assert g.x_coord_of_grid_cell_zero == 10.0


@pytest.mark.parametrize("name", ["synthetic_grid6.dss", "synthetic_grid7.dss"])
def test_p12_synthetic_albers_record_is_not_shg(name):
    # Units "Meters  " (blanks kept by Heclib.holString) and origin 1000/2000:
    # Monolith returns "" for this record (P12 report section 8 item A).
    with dss.open(fixture_path(name)) as f:
        g = f.read_grid("/PUBLIC/ALBERS/PRECIP/01JAN2020:0000/01JAN2020:0100/SYNTH/")
        assert g.srs_definition == ""
        assert g.metadata["albers"]["units"] == "Meters"


def test_features_advertise_grid_srs_parity():
    """Consumers gate native grid routing on this flag (maintainer-approved name)."""
    assert isinstance(dss.FEATURES, frozenset)
    assert all(isinstance(name, str) for name in dss.FEATURES)
    assert "grid_srs_monolith_parity" in dss.FEATURES
    assert "FEATURES" in dss.__all__


def _f32_bits(v):
    return struct.unpack("<I", struct.pack("<f", v))[0]


def test_modern_albers_parameters_match_monolith():
    with dss.open(fixture_path("synthetic_albers7.dss")) as f:
        for tag, (datum, units, params) in MODERN_ALBERS.items():
            a = f.read_grid(path(tag)).metadata["albers"]
            assert (a["datum"], a["units"]) == (datum, units), tag
            got = [a[k] for k in ("first_standard_parallel", "second_standard_parallel",
                                  "central_meridian", "latitude_of_projection_origin",
                                  "false_easting", "false_northing")]
            assert [_f32_bits(v) for v in got] == [_f32_bits(v) for v in params], tag
