"""Collect the licence texts of every resolved Rust dependency, without embedding local paths.

    python scripts/dependency_notices.py            # writes licenses/dependencies/
    python scripts/dependency_notices.py --check    # fails if licenses/dependencies/ is stale

Covers every package in Cargo.lock (build, dev and every target), plus the two readers vendored
in-tree under vendor/. A crate that publishes no licence file takes the texts retained under
licenses/upstream/<name>-<version>/, recorded in licenses/UPSTREAM_NOTICES.json.

The wheel's own bundle, python/ras_commander_fast_dss/THIRD_PARTY_LICENSES.txt, is written by
scripts/third_party_licenses.py and covers the crates linked into the wheel.
"""
from pathlib import Path
import argparse
import json
import shutil
import subprocess

root = Path(__file__).resolve().parents[1]
NAMES = ("license", "licence", "copying", "notice", "unlicense", "copyright")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--format-version", "1"], cwd=root, text=True
    ))
    folder = root / "licenses/dependencies"
    vendored = (root / "vendor").resolve()
    rows = ["# Resolved Rust dependency notices", "",
            "Generated by `scripts/dependency_notices.py` from `Cargo.lock`. Rows marked *vendored* are",
            "the patched readers under `vendor/` (see `vendor/README.md` and `vendor/PATCHES.md`).", "",
            "| Package | Version | SPDX expression | Source |", "|---|---|---|---|"]
    expected = set()
    for package in sorted(metadata["packages"], key=lambda p: (p["name"], p["version"])):
        source = Path(package["manifest_path"]).parent.resolve()
        in_vendor = source.is_relative_to(vendored)
        if package.get("source") is None and not in_vendor:
            continue  # this repository's own crates: LICENSE at the root
        paths = {p for p in source.iterdir() if p.is_file() and p.name.lower().startswith(NAMES)}
        for sub in ("LICENSES", "licenses", "license"):
            if (source / sub).is_dir():
                paths |= {p for p in (source / sub).iterdir() if p.is_file()}
        if package.get("license_file"):
            path = (source / package["license_file"]).resolve()
            assert path.is_relative_to(source), package["name"]
            paths.add(path)
        if not paths:
            paths = {p for p in (root / "licenses/upstream" / f"{package['name']}-{package['version']}").glob("*")
                     if p.is_file()}
        assert paths, f"Review missing license text for {package['name']} {package['version']}"
        name = f"{package['name']}-{package['version']}"
        destination = folder / name
        kind = "vendored" if in_vendor else "crates.io"
        rows.append(f"| {package['name']} | {package['version']} | {package.get('license') or 'see notice'} | {kind} |")
        for path in sorted(paths):
            target = destination / path.name
            expected.add(target)
            if args.check:
                assert target.is_file(), str(target.relative_to(root))
                assert target.read_bytes().replace(b"\r\n", b"\n") == path.read_bytes().replace(b"\r\n", b"\n"), \
                    str(target.relative_to(root))
            else:
                destination.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(path, target)
    content = "\n".join(rows) + "\n"
    target = folder / "INDEX.md"
    present = {p for p in folder.rglob("*") if p.is_file() and p != target} if folder.exists() else set()
    if args.check:
        assert target.read_text(encoding="utf-8") == content, "licenses/dependencies/INDEX.md is stale"
        assert present == expected, sorted(str(p.relative_to(root)) for p in present ^ expected)
    else:
        for stale in present - expected:
            stale.unlink()
        target.write_text(content, encoding="utf-8", newline="\n")
    print(f"Dependency notices {'verified' if args.check else 'collected'}: {len(rows) - 7} packages")


if __name__ == "__main__":
    main()
